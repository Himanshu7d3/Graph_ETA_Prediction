@st.cache_data(show_spinner=False)
def load_prediction_metadata():

    dataset_path = os.path.join("Dataset", "delivery_data.csv")

    if not os.path.exists(dataset_path):
        return None

    raw = pd.read_csv(dataset_path)

    essential_cols = [
        "trip_uuid", "source_center", "destination_center",
        "route_type", "actual_time", "osrm_time"
    ]

    raw = raw.dropna(subset=essential_cols)
    raw = raw[
        (raw["actual_time"] > 0) &
        (raw["osrm_time"] > 0)
    ].copy()

    raw["trip_uuid"] = raw["trip_uuid"].astype(str)
    raw["source_center_raw"] = raw["source_center"].astype(str)
    raw["destination_center_raw"] = raw["destination_center"].astype(str)

    raw["trip_creation_time"] = pd.to_datetime(
        raw["trip_creation_time"], errors="coerce"
    )
    raw["trip_hour"] = raw["trip_creation_time"].dt.hour

    def _get_time_of_day(hour):
        if pd.isna(hour):
            return "Night"
        if 5 <= hour < 12:
            return "Morning"
        elif 12 <= hour < 17:
            return "Afternoon"
        elif 17 <= hour < 21:
            return "Evening"
        return "Night"

    raw["time_of_day"] = raw["trip_hour"].apply(_get_time_of_day)

    # Exactly match the notebook's trip-level split.
    trip_ids = raw["trip_uuid"].drop_duplicates().to_numpy()

    train_trips, test_trips = train_test_split(
        trip_ids,
        test_size=0.20,
        random_state=26
    )

    train_df = raw[raw["trip_uuid"].isin(train_trips)].copy()
    test_df = raw[raw["trip_uuid"].isin(test_trips)].copy()

    # Exactly match Cell 14's train-derived integer encodings.
    src_categories = pd.Index(
        train_df["source_center_raw"].astype(str).unique()
    )
    dst_categories = pd.Index(
        train_df["destination_center_raw"].astype(str).unique()
    )

    src_mapping = {
        hub: i for i, hub in enumerate(src_categories)
    }
    dst_mapping = {
        hub: i for i, hub in enumerate(dst_categories)
    }

    # Exactly reconstruct the notebook's OSRM baseline evaluation.
    osrm_actual = test_df["actual_time"].to_numpy()
    osrm_pred = test_df["osrm_time"].to_numpy()

    return {
        "src_mapping": src_mapping,
        "dst_mapping": dst_mapping,
        "train_hubs": set(src_mapping) | set(dst_mapping),
        "osrm_mae": mean_absolute_error(osrm_actual, osrm_pred),
        "osrm_r2": r2_score(osrm_actual, osrm_pred),
        "osrm_acc15": float(
            np.mean(
                np.abs(osrm_pred - osrm_actual) /
                np.maximum(np.abs(osrm_actual), 1e-6) <= 0.15
            ) * 100
        ),
    }


@st.cache_resource(show_spinner=False)
def load_model_assets(best_model_name):
    model_files = {
        "RF + Graph": "rf_graph_model.pkl",
        "CatBoost + Graph": "cb_graph_model.pkl",
        "XGBoost + Graph": "xgb_graph_model.pkl",
    }

    model_file = model_files.get(best_model_name, "xgb_graph_model.pkl")

    model_path = os.path.join(DATA_DIR, model_file)
    feat_path  = os.path.join(DATA_DIR, "enhanced_features.pkl")
    emb_path   = os.path.join(DATA_DIR, "embeddings.pkl")
    le_path    = os.path.join(DATA_DIR, "le_time.pkl")

    if all(
        os.path.exists(path)
        for path in [model_path, feat_path, emb_path, le_path]
    ):
        with open(model_path, "rb") as f:
            model = pickle.load(f)
        with open(feat_path, "rb") as f:
            features = pickle.load(f)
        with open(emb_path, "rb") as f:
            embeddings = pickle.load(f)
        with open(le_path, "rb") as f:
            le_time = pickle.load(f)

        return model, features, embeddings, le_time

    return None, None, None, None

